void check_adler32() {
    // [RFC 1950] A.3: Adler-32("") = 1 and Adler-32("Wikipedia") = 0x11E60398.
    TEST_EQ(ost2pst::util::adler32(ByteView()), 0x00000001u, "adler32 of nothing");
    const std::string wikipedia = "Wikipedia";
    TEST_EQ(ost2pst::util::adler32(view(reinterpret_cast<const uint8_t *>(wikipedia.data()),
                                       wikipedia.size())),
            0x11E60398u, "adler32 of Wikipedia");
    const std::string hi = "Hi";
    TEST_EQ(ost2pst::util::adler32(view(reinterpret_cast<const uint8_t *>(hi.data()), hi.size())),
            0x00FB00B2u, "adler32 of Hi");
}

void check_detection() {
    TEST_CHECK(ost2pst::util::zlib_header_present(view(kStored, sizeof(kStored))));
    TEST_CHECK(ost2pst::util::zlib_header_present(view(kFixed, sizeof(kFixed))));
    TEST_CHECK(ost2pst::util::zlib_header_present(view(kDynamic, sizeof(kDynamic))));
    // [RFC 1950] 2.2: the check field makes CMF/FLG a multiple of 31, not of 32. 0x789C is valid and
    // 0x789D is not, even though only one bit differs.
    TEST_CHECK(!ost2pst::util::zlib_header_present(view(kBadCheckBits, sizeof(kBadCheckBits))));
    // A heap node starts with ibHnpm and then bSig 0xEC ([MS-PST] 2.3.1.2), which is never a CMF/FLG pair.
    static const uint8_t heap_node[] = {0xD6, 0x01, 0xEC, 0xBC, 0x20, 0x00, 0x00, 0x00};
    TEST_CHECK(!ost2pst::util::zlib_header_present(view(heap_node, sizeof(heap_node))));
    static const uint8_t too_short[] = {0x78, 0x9C, 0x03, 0x00};
    TEST_CHECK(!ost2pst::util::zlib_header_present(view(too_short, sizeof(too_short))));
}

void check_roundtrip() {
    struct Case {
        const char *label;
        const uint8_t *bytes;
        size_t size;
        size_t plain_size;
        const char *prefix;
    };
    const Case cases[] = {
        {"stored", kStored, sizeof(kStored), 23, "Hello, OST! Hello, OST!"},
        {"fixed", kFixed, sizeof(kFixed), 2, "Hi"},
        {"dynamic", kDynamic, sizeof(kDynamic), 2438, "context node folder property context tab"},
        {"run length", kRunLength, sizeof(kRunLength), 2001, "AAAAAAAAAAAAAAAA"},
        {"two blocks", kTwoBlocks, sizeof(kTwoBlocks), 24, "first block second block"},
        {"15-bit code", kLongCode, sizeof(kLongCode), 1, "n"},
    };
    for (const Case &item : cases) {
        Result<ost2pst::util::ZlibStream> inflated =
            ost2pst::util::inflate_zlib(view(item.bytes, item.size));
        TEST_OK(inflated, item.label);
        if (!inflated.ok()) {
            continue;
        }
        TEST_EQ(inflated.value().data.size(), item.plain_size, item.label);
        const std::string head = as_text(inflated.value().data).substr(0, std::strlen(item.prefix));
        TEST_STR(head, item.prefix, item.label);
        // Every byte of the block has to be accounted for: nothing may go unread.
        TEST_EQ(inflated.value().consumed, item.size, item.label);
    }

    // An empty stream ends mid-byte, and [RFC 1950] puts the Adler-32 on the next byte boundary.
    Result<ost2pst::util::ZlibStream> empty =
        ost2pst::util::inflate_zlib(view(kEmpty, sizeof(kEmpty)));
    TEST_OK(empty, "empty stream");
    if (empty.ok()) {
        TEST_EQ(empty.value().data.size(), 0u, "empty stream length");
        TEST_EQ(empty.value().consumed, sizeof(kEmpty), "empty stream consumed");
    }
}

// The same bytes without the wrapper: what a raw DEFLATE reader has to handle.
void check_raw_deflate() {
    Result<std::vector<uint8_t>> stored =
        ost2pst::util::inflate_deflate(view(kStored + 2, sizeof(kStored) - 2 - 4));
    TEST_OK(stored, "raw stored");
    if (stored.ok()) {
        TEST_STR(as_text(stored.value()), "Hello, OST! Hello, OST!", "raw stored");
    }
    Result<std::vector<uint8_t>> dynamic =
        ost2pst::util::inflate_deflate(view(kDynamic + 2, sizeof(kDynamic) - 2 - 4));
    TEST_OK(dynamic, "raw dynamic");
    if (dynamic.ok()) {
        TEST_EQ(dynamic.value().size(), 2438u, "raw dynamic length");
    }
}
void check_errors() {
    // A CMF/FLG pair that is not a multiple of 31 is not a zlib stream at all.
    TEST_ERROR(ost2pst::util::inflate_zlib(view(kBadCheckBits, sizeof(kBadCheckBits))),
               ErrorKind::kBadSignature, "zlib.CMF", "bad check bits");

    // A wrong Adler-32 is reported at the checksum's own offset, not at the start of the block.
    const uint64_t base = 0x1000;
    TEST_ERROR(ost2pst::util::inflate_zlib(view(kBadAdler, sizeof(kBadAdler))), ErrorKind::kBadCrc,
               "zlib.adler32", "bad adler32");
    TEST_ERROR_OFFSET(ost2pst::util::inflate_zlib(view(kBadAdler, sizeof(kBadAdler), base)),
                      base + sizeof(kBadAdler) - 4, "bad adler32");

    // [RFC 1951] 3.2.4: NLEN is the one's complement of LEN.
    TEST_ERROR(ost2pst::util::inflate_zlib(view(kBadNlen, sizeof(kBadNlen))), ErrorKind::kBadField,
               "deflate.NLEN", "bad NLEN");

    // A stream cut short is a truncation with an offset inside the block, never a crash.
    TEST_ERROR(ost2pst::util::inflate_zlib(view(kTruncated, sizeof(kTruncated))),
               ErrorKind::kTruncated, "deflate.LEN", "truncated stored block");
    TEST_ERROR_OFFSET(ost2pst::util::inflate_zlib(view(kTruncated, sizeof(kTruncated), base)),
                      base + 7, "truncated stored block");

    // [RFC 1950] FDICT would put a DICTID between the header and the stream. No OST block measured here
    // carries one, so it is refused instead of guessed at.
    std::vector<uint8_t> preset(kStored, kStored + sizeof(kStored));
    preset[1] = 0x20; // CMF/FLG = 0x7820: still a multiple of 31, with FDICT set
    TEST_CHECK(ost2pst::util::zlib_header_present(view(preset)));
    TEST_ERROR(ost2pst::util::inflate_zlib(view(preset)), ErrorKind::kUnsupported, "zlib.FLG",
               "preset dictionary");

    // Bytes that look like a header and then decode to nothing.
    static const uint8_t garbage[] = {0x78, 0x9C, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF};
    TEST_ERROR(ost2pst::util::inflate_zlib(view(garbage, sizeof(garbage))), ErrorKind::kBadField,
               "deflate.BTYPE", "garbage stream");

    // [RFC 1951] 3.2.7: HCLEN = 4 gives lengths for symbols 16, 17, 18 and 0, all of them 1 bit
    // long, which needs four one-bit codes and only two exist.
    static const uint8_t oversubscribed[] = {0x78, 0x9C, 0x05, 0x00, 0x92, 0x04, 0x00, 0x00, 0x00, 0x01};
    TEST_ERROR(ost2pst::util::inflate_zlib(view(oversubscribed, sizeof(oversubscribed))),
               ErrorKind::kBadField, "deflate.HCLEN", "over-subscribed code-length code");
}

void check_output_cap() {
    // 313 bytes inflate to 300,000. The cap is a reported error, not a short read.
    TEST_ERROR(ost2pst::util::inflate_zlib(view(kBomb, sizeof(kBomb)), 4096), ErrorKind::kUnsupported,
               "deflate.output", "capped inflate");

    Result<ost2pst::util::ZlibStream> full = ost2pst::util::inflate_zlib(view(kBomb, sizeof(kBomb)));
    TEST_OK(full, "uncapped inflate");
    if (full.ok()) {
        TEST_EQ(full.value().data.size(), 300000u, "uncapped inflate length");
        TEST_EQ(full.value().consumed, sizeof(kBomb), "uncapped inflate consumed");
    }
}

// A block whose stream stops short of cb reports what is left over, which is what keeps "compressed
// block" apart from "compressed block with something after it".
void check_consumed() {
    std::vector<uint8_t> block(kStored, kStored + sizeof(kStored));
    block.push_back(0x00);
    block.push_back(0x00);
    block.push_back(0x00);
    block.push_back(0x00);
    Result<ost2pst::util::ZlibStream> inflated = ost2pst::util::inflate_zlib(view(block));
    TEST_OK(inflated, "block with trailing bytes");
    if (inflated.ok()) {
        TEST_EQ(inflated.value().consumed, sizeof(kStored), "trailing bytes consumed");
        TEST_EQ(block.size() - inflated.value().consumed, 4u, "trailing bytes left over");
    }
}


"""Generate checked-in native catalogs; no Python dependency for application builds."""
import argparse
import json
from pathlib import Path
import re

def render(source):
    langs = source['languages']
    assert set(langs) == {'en','zh-Hans','zh-Hant','ja','fr','it','es','de','ko'} and len(langs) == 9
    rows = source['strings']
    assert rows
    for key, values in rows.items():
        assert re.fullmatch('[a-z_]+', key) and len(values) == len(langs), key
        tokens = [sorted(re.findall(r'\{[0-9]+\}', v)) for v in values]
        assert all(t == tokens[0] for t in tokens), key
        assert all(isinstance(v, str) and v and '\x00' not in v for v in values), key
    lines = ['// Generated by scripts/generate_gui_strings.py. Do not edit.', '#pragma once',
             '#include <string_view>', '#include <array>', 'namespace ost2pst::gui {',
             'enum class Text { ' + ', '.join(rows) + ', kSize };',
             'struct Catalog { std::string_view locale; std::array<std::wstring_view, static_cast<size_t>(Text::kSize)> strings; };',
             'inline constexpr Catalog kCatalogs[] = {']
    for i, lang in enumerate(langs):
        lines += ['    {"'+lang+'", {']
        lines += ['        L'+json.dumps(values[i], ensure_ascii=True)+',' for values in rows.values()]
        lines += ['    }},']
    lines += ['};', '} // namespace ost2pst::gui', '']
    return '\n'.join(lines)

if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    root = Path(__file__).resolve().parents[1]
    generated = render(json.loads((root/'resources/gui/catalogs.json').read_text(encoding='utf-8')))
    output = root/'resources/gui/strings.h'
    if a.check:
        assert output.read_bytes() == generated.encode('utf-8'), 'Catalog output is stale'
        print('Nine GUI catalogs and placeholders verified')
    else:
        output.write_bytes(generated.encode('utf-8'))
